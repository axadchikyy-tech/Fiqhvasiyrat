active_tasks = {}

async def send_questions(chat_id: int, savollar: list, mavzu_nomi: str):
    try:
        total = len(savollar)
        for index, savol in enumerate(savollar, start=1):
            await bot.send_message(chat_id, f"<b>{mavzu_nomi} викторинаси ({index}/{total}):</b>\n\n{savol}", parse_mode="HTML")
            if index < total:
                await asyncio.sleep(30)
    except Exception as e:
        logging.error(f"Хатолик юz берди: {e}")
    finally:
        if chat_id in active_tasks:
            del active_tasks[chat_id]

@dp.message(Command("tahorat"))
async def start_tahorat_quiz(message: Message):
    chat_id = message.chat.id
    if chat_id in active_tasks:
        await message.answer("⚠️ Викторина аллақачон бошланган ва давом этмоқда!")
        return
    await message.answer("✅ Таҳорат бўйича саволлар бошланди! Ҳар 30 сонияда янги савол ташлаб борилади.")
    task = asyncio.create_task(send_questions(chat_id, tahorat_savollari, "Таҳорат"))
    active_tasks[chat_id] = task

